"""
Власні винятки застосунку (п. 4.5 завдання).
Усі успадковують ValueError, тому існуючі блоки except ValueError продовжують працювати,
а View може відрізнити «помилку користувача» (BudgetError) від непередбаченої помилки програми.
"""


class BudgetError(ValueError):
    """Базовий виняток предметної області. Текст повідомлення показується користувачу."""


class ValidationError(BudgetError):
    """Некоректні дані: від'ємна чи нульова сума, неправильна дата, порожня категорія тощо."""


class CategoryError(BudgetError):
    """Неіснуюча, дубльована або використана в транзакціях категорія."""


class DataFileError(BudgetError):
    """Файл JSON не існує, пошкоджений або має неправильну структуру."""
