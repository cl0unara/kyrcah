def description_hints(category_name: str, kind: str = "Expense") -> list[str]:
    """Підказки для поля «Опис» (без підстановки місяця)."""
    items = DESCRIPTIONS.get(category_name) or GENERIC.get(kind, GENERIC["Expense"])
    return [text.replace(" за {month}", "").replace(", {month}", "").replace("{month}", "").strip() for text in items]


def random_description(category_name: str, kind: str, month_number: int, rng: random.Random) -> str:
    """Випадковий «людський» опис для категорії; {month} замінюється на місяць операції."""
    pool = DESCRIPTIONS.get(category_name) or GENERIC.get(kind, GENERIC["Expense"])
    return rng.choice(pool).replace("{month}", MONTHS_LOWER[month_number - 1])


def make_people(count: int, rng: random.Random) -> list[str]:
    """Набір унікальних користувачів «Ім'я Прізвище»."""
    names = set()
    attempts = 0
    while len(names) < count and attempts < count * 20:
        attempts += 1
        names.add(f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}")
    return sorted(names)
